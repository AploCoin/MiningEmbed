#include "MiningWork.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>
#include "sha3.h"
using namespace miningembed;
static unsigned yields = 0;
static unsigned randomCalls = 0;
static uint8_t observed[8][32];
static unsigned observations = 0;
static void cooperate() {
    ++yields;
}
static bool randomNonce(uint8_t* bytes, size_t length) {
    ++randomCalls;
    memset(bytes, 0x22, length);
    return true;
}
static bool failedRandom(uint8_t*, size_t) {
    return false;
}
static void zeroHash(const uint8_t*, size_t, uint8_t* digest) {
    memset(digest, 0, 32);
}
static void maxHash(const uint8_t*, size_t, uint8_t* digest) {
    memset(digest, 255, 32);
}
static void observeHash(const uint8_t* packed, size_t length, uint8_t* digest) {
    assert(length == 148 && observations < 8);
    memcpy(observed[observations++], packed + 20, 32);
    memset(digest, 255, 32);
}

int main() {
    MinerParams params;
    params.valid = true;
    params.lastBlock = 42;
    memset(params.signer, 0x11, 20);
    memset(params.target, 255, 32);
    memset(params.prevHash, 0x44, 32);
    params.totalMined[0] = 0x80;
    params.totalMined[31] = 1;
    uint8_t nonce[32];
    uint8_t digest[33];
    uint8_t expected[32];
    memset(nonce, 0x22, 32);
    memset(digest, 0xAA, sizeof(digest));
    // Independent vector generated by WebMiner's installed Web3 encodePacked + keccak256.
    assert(decodeHex("03cfcacd894696f7035c865b01e6cce83e12b4d6f8f8949326ed66de5ffd3cd5", expected,
                     32, 32));
    assert(hashNonce(params, nonce, 32, digest, 32, keccak_256));
    assert(memcmp(expected, digest, 32) == 0 && digest[32] == 0xAA);
    assert(validProof(params, nonce, 32, keccak_256));
    assert(!hashNonce(params, nonce, 31, digest, 32, keccak_256));
    memset(digest, 0xAA, sizeof(digest));
    assert(!hashNonce(params, nonce, 32, digest, 31, keccak_256));
    assert(digest[0] == 0xAA && digest[32] == 0xAA);
    assert(!decodeHex("0011", digest, 1, 2) && digest[0] == 0xAA);
    assert(!decodeHex("00xz", digest, 2, 2) && digest[0] == 0xAA);
    assert(!decodeHex("00", digest, 2, 2));
    assert(!decodeHex(nullptr, digest, 2, 2));
    assert(decodeHex("0X0011", digest, 2, 2) && digest[0] == 0 && digest[1] == 0x11);
    assert(sameChallenge(params, params));
    for (int field = 0; field < 6; ++field) {
        MinerParams changed = params;
        switch (field) {
        case 0:
            ++changed.lastBlock;
            break;
        case 1:
            changed.target[0] ^= 1;
            break;
        case 2:
            changed.prevHash[31] ^= 1;
            break;
        case 3:
            changed.totalMined[0] ^= 1;
            break;
        case 4:
            changed.signer[0] ^= 1;
            break;
        case 5:
            changed.valid = false;
            break;
        }
        assert(!sameChallenge(params, changed));
    }
    Candidate out;
    assert(search(params, 2000, out, keccak_256, randomNonce, cooperate) == WorkResult::Found);
    assert(out.valid && sameChallenge(params, out.params) && memcmp(out.hash, expected, 32) == 0);
    yields = 0;
    randomCalls = 0;
    assert(search(params, 2000, out, maxHash, randomNonce, cooperate) == WorkResult::Exhausted);
    assert(!out.valid && randomCalls == 1 && yields == 33);
    SearchCursor cursor;
    uint32_t tested = 999;
    randomCalls = observations = 0;
    assert(search(params, 2, out, observeHash, randomNonce, cooperate, &cursor, &tested) ==
           WorkResult::Exhausted);
    assert(tested == 2 && randomCalls == 1);
    assert(search(params, 2, out, observeHash, randomNonce, cooperate, &cursor, &tested) ==
           WorkResult::Exhausted);
    assert(tested == 2 && randomCalls == 1 && observations == 4);
    for (unsigned i = 0; i < 4; ++i) {
        assert(memcmp(observed[i], nonce, 31) == 0 && observed[i][31] == 0x22 + i);
    }
    MinerParams changed = params;
    changed.prevHash[0] ^= 1;
    assert(search(changed, 1, out, observeHash, randomNonce, cooperate, &cursor, &tested) ==
           WorkResult::Exhausted);
    assert(tested == 1 && randomCalls == 2 && memcmp(observed[4], nonce, 32) == 0);
    assert(search(params, 2, out, zeroHash, randomNonce, cooperate, &cursor, &tested) ==
           WorkResult::Found);
    assert(tested == 1 && out.valid);
    cursor.initialized = false;
    assert(search(params, 2, out, zeroHash, failedRandom, cooperate, &cursor, &tested) ==
           WorkResult::RandomUnavailable);
    assert(tested == 0 && !out.valid);
    assert(search(params, 1, out, zeroHash, failedRandom, cooperate) ==
           WorkResult::RandomUnavailable);
    assert(!out.valid);
    assert(search(params, 0, out, zeroHash, randomNonce, cooperate) == WorkResult::InvalidArgument);
    assert(search(params, 2001, out, zeroHash, randomNonce, cooperate) ==
           WorkResult::InvalidArgument);
    assert(search(params, 1, out, zeroHash, randomNonce, nullptr) == WorkResult::InvalidArgument);
    memset(params.target, 0, 32);
    assert(!validProof(params, nonce, 32, zeroHash)); // equality must not pass
    assert(search(params, 1, out, zeroHash, randomNonce, cooperate) == WorkResult::Exhausted);
    printf("portable work: vector, uint256 count, buffers, RNG failure, strict target, stale "
           "challenge and yield passed\n");
}
